/**
 * The vocabulary of the LMS boundary.
 *
 * These types are deliberately **ours**, not Moodle's. Nothing here mirrors a
 * Moodle web-service payload — no `fullname`, no `enrolledusercount`, no
 * `completionstatus`. Translating Moodle's shapes into these is the job of the
 * real adapter in Phase 2, and it is what makes this module an anti-corruption
 * layer rather than a thin proxy (CLAUDE.md §2A).
 *
 * The practical test: if swapping the LMS required changing anything outside
 * `src/moodle`, the boundary has leaked.
 */

/** An LMS-side user identifier. Our `users.moodle_user_id`. */
export type LmsUserId = number;

/** An LMS-side course identifier. Our `courses.moodle_course_id`. */
export type LmsCourseId = number;

export interface LmsHealth {
  reachable: boolean;
  /** Present only when reachable; useful for the Phase 5 health dashboard. */
  siteName?: string;
  lmsVersion?: string;
  /** Populated when unreachable. A code, never a raw driver/HTTP error, so
   *  connection details cannot reach a response or a log. */
  failureCode?: 'UNREACHABLE' | 'UNAUTHORISED' | 'UNEXPECTED_RESPONSE';
}

export interface ProvisionUserInput {
  email: string;
  fullName: string;
  /** Our user id, passed so the adapter can set a stable external reference. */
  externalUserId: string;
}

export interface LmsUserRef {
  lmsUserId: LmsUserId;
  email: string;
  /** The LMS's own record of the display name — read back, not echoed from a
   *  caller's input, so it reflects what Moodle actually holds (the same
   *  "read back rather than synthesise" rule `createCourse` follows). */
  fullName: string;
}

/** What a profile edit can change about the LMS's copy of a user (§4.12). */
export interface UpdateUserInput {
  lmsUserId: LmsUserId;
  fullName: string;
}

export interface LmsCourse {
  lmsCourseId: LmsCourseId;
  /** Arabic title as authored in the LMS. */
  title: string;
  summary: string;
  /** Nominal effort in minutes, or null when the LMS does not express one. */
  durationMinutes: number | null;
  /** Whether the LMS currently shows this course to learners. Our own
   *  `courses.status` is separate product metadata and is not this. */
  visible: boolean;
}

/**
 * What an entity supplies to create a course shell (§4B.3, D-060).
 *
 * Deliberately only what the LMS needs to bring a course into existence. Path
 * membership, the RIASEC letter, duration, objectives, prerequisites and
 * language are **ours** (D-035, D-039) and are absent here — putting them on
 * this input would make the adapter responsible for data Moodle does not model,
 * which is the mistake D-035 already ruled out once.
 */
export interface CreateCourseInput {
  title: string;
  summary: string;
  /**
   * A short unique code. Moodle requires one and rejects a duplicate, so it is
   * generated by the caller rather than derived from the title — two entities
   * naming a course the same thing must not collide.
   */
  shortName: string;
}

/**
 * Why an entity is being put into a course.
 *
 * `LEARNER` takes a course; `AUTHOR` writes one and needs Moodle's editing
 * capabilities (D-060). Expressed as our own word rather than as a Moodle role
 * id, because role ids are per-instance configuration the adapter resolves — a
 * caller passing `3` would be encoding one Moodle installation's numbering into
 * the application layer.
 */
export type LmsEnrolmentRole = 'LEARNER' | 'AUTHOR';

export interface EnrolInput {
  lmsUserId: LmsUserId;
  lmsCourseId: LmsCourseId;
  /** Defaults to `LEARNER`, which is what every Phase 1-3 caller meant. */
  role?: LmsEnrolmentRole;
}

/**
 * What the LMS holds inside a course, as far as we need to know (§4B.4, D-061).
 *
 * **This exists to answer one question before an entity publishes: can a learner
 * on this course ever actually finish it?** D-042 found the failure it guards
 * against — a Moodle course with no completion criteria configured reports
 * `completed: false` forever, so nobody on it can pass and no certificate can
 * ever be issued, with nothing in any log to explain it. Phase 2 could only
 * detect that after the fact, from a learner already stuck on it.
 *
 * Deliberately a summary and not a content tree. We do not render Moodle's
 * material (D-000/D-045), so anything richer would be data with no consumer —
 * and modelling Moodle's module structure here would leak its schema across the
 * boundary D-030 exists to hold.
 */
export interface LmsCourseContentSummary {
  lmsCourseId: LmsCourseId;
  /** Total activities across all sections. */
  activityCount: number;
  /** Whether at least one of them is a quiz. */
  hasQuiz: boolean;
  /**
   * Whether course completion is switched on **and** at least one criterion is
   * configured. Both halves matter: completion enabled with no criteria is the
   * same silent dead end as completion disabled.
   */
  completionConfigured: boolean;
}

/**
 * Raw progress for one user in one course.
 *
 * Note what is absent: any notion of *passing*. The pass threshold is a product
 * setting evaluated against the grade the LMS returns (D-007), so this type
 * carries `gradePercent` and never a `passed` boolean. If the LMS decided
 * pass/fail, changing certification policy would mean editing quizzes in Moodle.
 */
export interface LmsCourseProgress {
  lmsUserId: LmsUserId;
  lmsCourseId: LmsCourseId;
  /** The LMS's own course-completion signal. */
  completed: boolean;
  completedAt: Date | null;
  /** 0–100, or null when the course has no graded activity yet attempted. */
  gradePercent: number | null;
}

/** Raised by the module when the LMS is configured but unusable. */
export class LmsUnavailableError extends Error {
  constructor(readonly failureCode: NonNullable<LmsHealth['failureCode']>) {
    super(`LMS_${failureCode}`);
    this.name = 'LmsUnavailableError';
  }
}

/**
 * Raised when the LMS is reachable and answered, but *refused* the operation —
 * a hand-created account already holding the address, a course that will not
 * accept an enrolment.
 *
 * Distinct from `LmsUnavailableError` because the operational response differs:
 * an outage is retried, a refusal needs a human. The underlying LMS error code
 * is deliberately **not** carried here — it is LMS vocabulary and would leak the
 * boundary (D-030). It is written to the log inside the module instead, where an
 * operator can find it and a caller cannot couple to it.
 */
export class LmsOperationError extends Error {
  constructor(
    readonly operation: 'PROVISION' | 'ENROL' | 'SYNC' | 'CREATE_COURSE' | 'UPDATE_USER',
  ) {
    super(`LMS_${operation}_REJECTED`);
    this.name = 'LmsOperationError';
  }
}
