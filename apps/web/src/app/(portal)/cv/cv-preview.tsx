'use client';

import { useMemo } from 'react';
import { useTranslations } from 'next-intl';

import {
  RIASEC_LETTERS,
  cvDocumentBody,
  cvDocumentCss,
  type CvAutofill,
  type CvProfile,
  type RiasecLetter,
} from '@tamkeen/types';

/**
 * The live preview (§4.11).
 *
 * **It renders the same function the PDF prints.** `cvDocumentBody` and
 * `cvDocumentCss` live in `@tamkeen/types` precisely so there is one layout
 * rather than two — a preview that differs from the export is worse than no
 * preview, because it promises the learner something the file will not deliver.
 *
 * The markup is generated by our own code and every interpolated value is
 * escaped inside `cvDocumentBody`, which is what makes `dangerouslySetInnerHTML`
 * the right tool here rather than a hazard: rebuilding the same layout as JSX
 * would be the second implementation this exists to avoid.
 *
 * `zoom` scales the A4-width document into the panel. Unlike `transform:
 * scale()` it reflows layout, so the preview occupies the space it actually
 * needs instead of leaving a scaled-down block in a full-size box — and line
 * breaks land where they will land on the page.
 */
export function CvPreview({ profile, autofill }: { profile: CvProfile; autofill: CvAutofill }) {
  const t = useTranslations('cv');
  const tRiasec = useTranslations('riasec');

  /* D-050: RIASEC type names pass through as authored, and the catalogue is
     where the Arabic lives (D-024) — so they are read here rather than being
     duplicated into the shared renderer. */
  const riasecNames = useMemo(
    () =>
      Object.fromEntries(
        RIASEC_LETTERS.map((letter) => [letter, tRiasec(`${letter}.name`)]),
      ) as Record<RiasecLetter, string>,
    [tRiasec],
  );

  const html = useMemo(
    () => cvDocumentBody({ profile, autofill, riasecNames }),
    [profile, autofill, riasecNames],
  );

  return (
    <section aria-labelledby="cv-preview-heading" className="flex flex-col gap-2">
      <h2 id="cv-preview-heading" className="text-sm font-semibold text-foreground">
        {t('previewTitle')}
      </h2>
      <p className="text-xs text-muted-foreground">{t('previewNote')}</p>

      <style>{cvDocumentCss()}</style>

      <div className="overflow-auto rounded-card border border-border bg-card shadow-sm">
        <div style={{ zoom: 0.62 }} className="w-[210mm]">
          {/*
            `aria-hidden`: the preview is a visual rendering of data the form
            already exposes as labelled fields. Announcing every value twice
            would make the page longer to navigate for no gain.
          */}
          <div
            aria-hidden="true"
            className="cv-document"
            dangerouslySetInnerHTML={{ __html: html }}
          />
        </div>
      </div>
    </section>
  );
}
